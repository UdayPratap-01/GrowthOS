#!/usr/bin/env python
"""
End-to-end verification for the P2-A creative and campaign engine.

Why this exists alongside the test suite: the tests drive handlers directly so
they stay fast and deterministic. This script instead drives the *deployed*
shape of the system — HTTP requests in one place, the real `Worker` process loop
draining the queue in another — and then reads the generated bytes back out of
object storage through the authenticated API. That is the only way to show the
pipeline works end to end rather than showing that each piece works in isolation.

It refuses to overstate its result. The provider actually in use is reported as
REAL, DEMO or NOT_CONFIGURED, and a run against the demo provider is labelled as
such: it proves storage, retrieval, authorization and the job pipeline, and
proves nothing whatsoever about a real vendor's output.

    # against the local SQLite database
    python scripts/verify_p2a_e2e.py

    # against PostgreSQL
    DATABASE_URL="postgresql+asyncpg://growthos:growthos@127.0.0.1:55433/growthos_p2a" \
      python scripts/verify_p2a_e2e.py

Exit code 0 means every check passed. 1 means a check failed. 2 means the script
could not run.
"""

